-- Verify current prices and discounts, validate stock, and save the order atomically.
create or replace function public.place_order(p_customer_name text,p_phone text,p_address text,p_city text,p_postal_code text,p_items jsonb)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_user uuid:=auth.uid(); v_order bigint; v_total numeric(10,2):=0; v_item jsonb; v_product public.products%rowtype; v_quantity numeric(8,2); v_live_price numeric(10,2);
begin
  if v_user is null then raise exception 'Sign in to place an order'; end if;
  if length(trim(p_customer_name))<2 or length(trim(p_phone))<6 or length(trim(p_address))<5 or length(trim(p_city))<2 or length(trim(p_postal_code))<3 then raise exception 'Please enter complete delivery details'; end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)<1 or jsonb_array_length(p_items)>30 then raise exception 'Your bag is empty or too large'; end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    if v_item->>'product_id' is null or v_item->>'quantity' is null then raise exception 'Invalid fabric in your bag'; end if;
    v_quantity:=(v_item->>'quantity')::numeric;
    if v_quantity<1 or v_quantity>100 then raise exception 'Order quantity must be between 1 and 100 metres'; end if;
    select * into v_product from public.products where id=(v_item->>'product_id')::bigint and is_active=true for update;
    if not found then raise exception 'A fabric is no longer available'; end if;
    if v_quantity>v_product.stock_meters then raise exception 'Not enough stock for %',v_product.name; end if;
    v_live_price:=round(v_product.price*(1-v_product.discount_percent/100),2);
    v_total:=v_total+v_live_price*v_quantity;
  end loop;
  insert into public.orders(user_id,total_amount,customer_name,phone,delivery_address,city,postal_code)
    values(v_user,v_total,trim(p_customer_name),trim(p_phone),trim(p_address),trim(p_city),trim(p_postal_code)) returning id into v_order;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_quantity:=(v_item->>'quantity')::numeric;
    select * into v_product from public.products where id=(v_item->>'product_id')::bigint for update;
    v_live_price:=round(v_product.price*(1-v_product.discount_percent/100),2);
    insert into public.order_items(order_id,product_id,product_name,unit_price,quantity,unit)
      values(v_order,v_product.id,v_product.name,v_live_price,v_quantity,'metre');
    update public.products set stock_meters=stock_meters-v_quantity where id=v_product.id;
  end loop;
  return jsonb_build_object('order_id',v_order,'total_amount',v_total);
end; $$;
revoke all on function public.place_order(text,text,text,text,text,jsonb) from public;
grant execute on function public.place_order(text,text,text,text,text,jsonb) to authenticated;
