-- Bukhari Fabrics catalogue, admin access, product galleries, and metre-based orders.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'lawn',
  description text not null default '',
  price numeric(10,2) not null check(price >= 0),
  image_url text not null,
  images text[] not null default '{}',
  badge text,
  rating numeric(2,1) not null default 4.8 check(rating between 0 and 5),
  is_new boolean not null default false,
  is_featured boolean not null default false,
  discount_percent numeric(5,2) not null default 0 check(discount_percent between 0 and 90),
  stock_meters numeric(10,2) not null default 0 check(stock_meters >= 0),
  is_active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  constraint products_category_check check(category in ('lawn','ivory','linen','silk','winter','luxury'))
);

